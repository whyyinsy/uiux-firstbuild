export function formatSymbolPrice(sym: MarketSymbol): string {
  const formatted = sym.price.toLocaleString('en-US', {
    minimumFractionDigits: sym.decimals,
    maximumFractionDigits: sym.decimals,
  });
  return `${sym.prefix ?? ''}${formatted}${sym.suffix ?? ''}`;
}

export function formatRawPrice(price: number, decimals: number, prefix = '', suffix = ''): string {
  const formatted = price.toLocaleString('en-US', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  });
  return `${prefix}${formatted}${suffix}`;
}

export function generateCandlesForSymbol(symbol: MarketSymbol, timeframe: Timeframe, count = 64): CandlePoint[] {
  const seedBase = symbol.id.split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
  const tfMultiplier: Record<Timeframe, number> = {
    '1m': 0.0012,
    '5m': 0.0022,
    '15m': 0.0038,
    '1H': 0.0065,
    '4H': 0.011,
    '1D': 0.016,
    '1W': 0.028,
  };
  const stepMs: Record<Timeframe, number> = {
    '1m': 60_000,
    '5m': 300_000,
    '15m': 900_000,
    '1H': 3_600_000,
    '4H': 14_400_000,
    '1D': 86_400_000,
    '1W': 604_800_000,
  };

  const vol = tfMultiplier[timeframe];
  const candles: CandlePoint[] = [];
  const endPrice = symbol.price;
  const trendBias = symbol.changePct >= 0 ? 1 : -1;

  // Deterministic pseudo-random generator
  let seed = seedBase * 131 + timeframe.length * 97;
  const rand = () => {
    seed = (seed * 1664525 + 1013904223) % 4294967296;
    return seed / 4294967296;
  };

  // Build backwards then reverse so final close matches live price cleanly
  let cursorClose = endPrice;
  const now = new Date('2026-11-25T16:00:00Z').getTime();

  const rawPoints: CandlePoint[] = [];
  for (let i = 0; i < count; i++) {
    const deltaRatio = (rand() - 0.48 - trendBias * 0.04) * vol;
    const open = cursorClose / (1 + deltaRatio);
    const bodyMax = Math.max(open, cursorClose);
    const bodyMin = Math.min(open, cursorClose);
    const wickUp = bodyMax * (rand() * vol * 0.6);
    const wickDown = bodyMin * (rand() * vol * 0.6);
    const high = bodyMax + wickUp;
    const low = Math.max(0.0001, bodyMin - wickDown);

    const ts = new Date(now - i * stepMs[timeframe]);
    const timeLabel =
      timeframe === '1D' || timeframe === '1W'
        ? ts.toLocaleDateString('en-US', { month: 'short', day: 'numeric' })
        : ts.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', hour12: false });

    rawPoints.push({
      time: timeLabel,
      open,
      high,
      low,
      close: cursorClose,
      volume: Math.round((0.4 + rand() * 1.4) * 1000),
    });

    cursorClose = open;
  }

  for (let i = rawPoints.length - 1; i >= 0; i--) {
    candles.push(rawPoints[i]);
  }
  return candles;
}
